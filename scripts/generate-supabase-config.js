const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const envPath = path.join(projectRoot, '.env');
const configPath = path.join(projectRoot, 'supabase-config.js');

function loadEnv(filePath) {
  if (!fs.existsSync(filePath)) return {};

  return fs.readFileSync(filePath, 'utf8').split(/\r?\n/).reduce((env, line) => {
    const match = line.match(/^\s*(?:export\s+)?([A-Z][A-Z0-9_]*)\s*=\s*(.*)\s*$/);
    if (!match) return env;

    const value = match[2].replace(/^(['"])(.*)\1$/, '$2');
    env[match[1]] = value;
    return env;
  }, {});
}

const env = { ...loadEnv(envPath), ...process.env };
const adminEmails = (env.ADMIN_EMAILS || '')
  .split(',')
  .map(email => email.trim())
  .filter(Boolean);

const requiredVariables = ['SUPABASE_URL', 'SUPABASE_ANON_KEY', 'ADMIN_EMAILS', 'FINANCE_ADMIN_EMAIL'];
const missingVariables = requiredVariables.filter(name => !env[name]);

if (missingVariables.length > 0) {
  console.error(`Missing environment variables: ${missingVariables.join(', ')}`);
  process.exit(1);
}

const config = {
  url: env.SUPABASE_URL.replace(/\/+$/, ''),
  anonKey: env.SUPABASE_ANON_KEY,
  adminEmails,
  financeAdminEmail: env.FINANCE_ADMIN_EMAIL.trim()
};

const configFile = `// Generated from .env. Do not edit this file directly.\nwindow.SUPABASE_CONFIG = ${JSON.stringify(config, null, 2)};\n\nwindow.SUPABASE_CLIENT = window.supabase\n  ? window.supabase.createClient(window.SUPABASE_CONFIG.url, window.SUPABASE_CONFIG.anonKey)\n  : null;\n`;

fs.writeFileSync(configPath, configFile);
console.log('Generated supabase-config.js from .env');